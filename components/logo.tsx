/* ------------------------------------------------------------------
   The company logo, vectorised from the artwork the client supplied.

   The outlines are the real letterforms — traced from the original, so this
   is the logo itself and not the Arial-Narrow approximation that stood here
   before. The trace carries one colour, so the two brand colours are put back
   the only way a single-colour trace allows: a green field laid behind the
   globe, showing through wherever the trace left the artwork open. The blue
   comes from `currentColor`, which is what lets the mark lift in the dark
   theme instead of disappearing into the sidebar.

   Coordinates come straight from the trace: paths live in a 10x space that is
   flipped by the group transform, so every box below is quoted in the final
   viewBox space and the group is left exactly as the tracer emitted it.
   ------------------------------------------------------------------ */

/** The globe interior, drawn under the outlines so the openings in the trace
 *  read as the globe's own colour.
 *
 *  The box is measured, not guessed: probing the traced path with
 *  isPointInFill puts the inner walls at x 214.5 and 244 and the inner caps at
 *  y 51.5 and 181.75, so the field is inset half a unit inside those to keep
 *  antialiasing off the outline. */
const FIELD = { x: 215, y: 52, w: 28.5, h: 129.5 } as const
function GlobeField() {
  return <rect x={FIELD.x} y={FIELD.y} width={FIELD.w} height={FIELD.h} rx={FIELD.w / 2} fill="var(--brand-green)" />
}

